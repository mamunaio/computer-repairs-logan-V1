"""Generate .pages.yml for computer-repairs-logan.

Pages CMS renders a collection by pulling the full text of every file in the
folder in one request. src/data/pages is 102 files / 1.2 MB, which comes back
empty. Individual `file` entries fetch one file each, so they work — this
emits one per page, grouped for the sidebar.
"""
import os, glob, io

PAGES = 'src/data/pages'
SUBURB_PREFIX = 'computer-repairs-'
MAIN = {'services', 'contact', '404'}

ACRONYMS = {
    '3d': '3D', 'ai': 'AI', 'cctv': 'CCTV', 'it': 'IT', 'nbn': 'NBN',
    'hp': 'HP', 'msi': 'MSI', 'ups': 'UPS', 'nas': 'NAS', 'isp': 'ISP',
    'seo': 'SEO', 'tv': 'TV', 'pc': 'PC', 'os': 'OS', '2fa': '2FA',
    'onedrive': 'OneDrive', 'macbook': 'MacBook',
}

def label_for(slug, kind):
    if kind == 'suburb':
        s = slug[len(SUBURB_PREFIX):]
    else:
        s = slug[:-len('-logan')] if slug.endswith('-logan') else slug
    return ' '.join(ACRONYMS.get(w, w.capitalize()) for w in s.split('-'))

slugs = sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob(f'{PAGES}/*.json'))

home, main, suburbs, services = [], [], [], []
for s in slugs:
    if s == 'index':
        home.append(s)
    elif s in MAIN:
        main.append(s)
    elif s.startswith(SUBURB_PREFIX) and s != 'computer-repairs-logan':
        suburbs.append(s)
    else:
        services.append(s)

def entry(slug, kind, indent):
    pad = ' ' * indent
    lbl = 'Home' if slug == 'index' else label_for(slug, kind)
    # Quoted so purely numeric slugs like 404 stay strings, not YAML integers.
    return (
        f"{pad}- name: \"{slug}\"\n"
        f"{pad}  label: \"{lbl}\"\n"
        f"{pad}  type: file\n"
        f"{pad}  path: {PAGES}/{slug}.json\n"
        f"{pad}  format: json\n"
        f"{pad}  fields:\n"
        f"{pad}    - name: bodyHtml\n"
        f"{pad}      component: pageBody\n"
        f"{pad}    - name: headHtml\n"
        f"{pad}      component: pageHead\n"
    )

def group(name, lbl, slugs_, kind, desc=None):
    out = f"  - name: {name}\n    label: {lbl}\n    type: group\n"
    if desc:
        out += f"    description: {desc}\n"
    out += "    items:\n"
    out += ''.join(entry_or_converted(s, kind, 6) for s in slugs_)
    return out

header = """# Pages CMS configuration — https://pagescms.org/docs
#
# Browser-based editing for computerrepairslogan.com.au.
# app.pagescms.org -> computer-repairs-logan -> pick a page -> edit -> Save.
# Saving commits to main, which triggers the Cloudflare Pages build.
#
# Why every page is listed individually instead of as one collection:
# Pages CMS builds a collection listing by fetching the full text of every
# file in the folder in a single request. src/data/pages is 102 files and
# 1.2 MB, which comes back empty (Files cached: 0, status Ok, no error).
# A `file` entry fetches only that one file, so these work. This file is
# generated by scripts/gen-pages-yml.py — rerun it after adding a page.
#
# Editing is raw HTML on purpose. The layout hangs off the class names in
# that markup (hero, wrap, badge, lead, accent). A rich-text editor would
# re-serialise the HTML and strip them, the same failure mode as
# JSON-decoding Elementor data. Change the words between the tags; leave
# the tags and class names alone.

settings:
  cache: true

media:
  input: public/images
  output: /images

components:
  pageBody:
    label: Page content
    description: >-
      The visible page. Edit the text between the tags. Do not change the tags
      or their class names, and do not paste formatted text from Word or a
      website, it brings hidden markup with it.
    type: code
    options:
      format: html
  pageHead:
    label: Search listing and schema
    description: >-
      The <title> and meta description here are what Google shows in search
      results. Keep the title under about 60 characters and the description
      between 120 and 160. The JSON-LD block at the bottom feeds the Google
      business panel, check it at validator.schema.org after changing it.
    type: code
    options:
      format: html

content:
"""

# Pages already converted to structured fields get a hand-written entry from
# config/, because their JSON no longer holds bodyHtml/headHtml. Declaring the
# old two-field shape against a converted page would blank it on save.
CONVERTED_DIR = 'scripts/pages-yml-entries'

def converted(slug):
    path = os.path.join(CONVERTED_DIR, f'{slug}.yml')
    return io.open(path, encoding='utf-8').read().rstrip() + '\n' if os.path.exists(path) else None

def entry_or_converted(slug, kind, indent):
    return converted(slug) or entry(slug, kind, indent)

body = ''.join(entry_or_converted(s, 'main', 2) for s in home)
body += group('main_pages', 'Main pages', main, 'main')
body += group('service_pages', f'Services ({len(services)})', services, 'service')
body += group('suburb_pages', f'Suburbs ({len(suburbs)})', suburbs, 'suburb')

with io.open('.pages.yml', 'w', encoding='utf-8', newline='\n') as f:
    f.write(header + body)

print(f'home={len(home)} main={len(main)} services={len(services)} suburbs={len(suburbs)} total={len(slugs)}')
